-- ShopFast: four more INTENTIONALLY VULNERABLE patterns (SF-09..SF-12).
-- Each is a mistake AI coding tools commonly produce on Supabase. This migration
-- is applied by the same throwaway local stack the proofs run against.

-- ===========================================================================
-- SF-09  Storage bucket: any signed-in user can read any other user's object
-- ===========================================================================
-- A private "receipts" bucket holds each customer's purchase receipts. The
-- SELECT policy below was meant to say "a signed-in customer can read their
-- receipts", but it checks only that the caller is authenticated, not that the
-- object is theirs. So customer B can download customer A's receipt.
insert into storage.buckets (id, name, public)
  values ('receipts', 'receipts', false)
  on conflict (id) do nothing;

-- PLANTED SF-09: this SELECT policy lets ANY authenticated user read ANY object
-- in the receipts bucket (no owner / path check), not just their own.
create policy "receipts are readable by signed-in users"
  on storage.objects for select to authenticated
  using (bucket_id = 'receipts');

-- Uploads are done server-side (service role) during seeding, so no INSERT
-- policy is needed; the flaw being proven is read access, not write.

-- ===========================================================================
-- SF-10  Realtime: a signed-in user receives another user's rows over Realtime
-- ===========================================================================
-- "notifications" is streamed to the browser over Supabase Realtime so each
-- customer sees their order updates live. RLS is ON here (unlike SF-02), which
-- looks safe, but the SELECT policy returns true for every signed-in user, and
-- Realtime authorises Postgres Changes with that same policy. So customer B's
-- subscription receives customer A's rows as they are inserted.
create table public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id),
  body text not null,
  created_at timestamptz not null default now()
);

alter table public.notifications enable row level security;

-- PLANTED SF-10: policy is `using (true)` instead of `using (auth.uid() = user_id)`.
-- Realtime checks this same policy per subscriber, so everyone receives everyone's rows.
create policy "notifications readable by any signed-in user"
  on public.notifications for select to authenticated
  using (true);

-- Publish the table to Realtime so Postgres Changes are broadcast.
alter publication supabase_realtime add table public.notifications;

-- ===========================================================================
-- SF-11  SECURITY DEFINER RPC returns another user's order, bypassing RLS
-- ===========================================================================
-- "invoices" does RLS the right way: it is ON and the policy is owner-only, so
-- a direct read of someone else's invoice returns nothing. But the helper RPC
-- below runs as SECURITY DEFINER (with the owner's rights, bypassing RLS) and
-- never checks who is calling, so any signed-in user can read any invoice.
create table public.invoices (
  id bigint generated by default as identity (start with 9001) primary key,
  order_id bigint references public.orders(id),
  user_id uuid not null references public.profiles(id),
  amount_cents integer not null,
  billing_address text,
  created_at timestamptz not null default now()
);

alter table public.invoices enable row level security;

-- A correct, owner-only SELECT policy: a direct read of another user's invoice
-- returns zero rows. This is what makes the RPC bypass below a real flaw.
create policy "invoices are owner-only" on public.invoices for select to authenticated
  using (auth.uid() = user_id);

-- PLANTED SF-11: SECURITY DEFINER runs with the function owner's rights, so it
-- ignores the owner-only policy above. It takes an invoice id and returns that
-- invoice with NO check that the caller owns it (no `auth.uid() = user_id`).
create function public.get_invoice(p_invoice_id bigint)
  returns public.invoices
  language sql
  security definer
  set search_path = ''
as $$
  select * from public.invoices where id = p_invoice_id;
$$;

grant execute on function public.get_invoice(bigint) to anon, authenticated;

-- ===========================================================================
-- SF-12  AI support tool acts on the model's argument, not the session user
-- ===========================================================================
-- Product reviews are customer-generated text. The AI support assistant
-- (app/api/support) feeds a product's reviews to the model as context and gives
-- the model an `lookup_order` tool that runs with SERVER privileges. The tool
-- uses the order id the MODEL supplies, never the signed-in user's identity, so
-- attacker text planted in a review can make the assistant fetch and reveal
-- another customer's order. See app/api/support/route.ts and poc/standins.mjs
-- for the scripted-model note.
create table public.reviews (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id),
  author text,
  body text not null,
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;
create policy "reviews are public" on public.reviews for select using (true);
